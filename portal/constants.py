"""
constants.py — فئات المانحين الثمان ونطاقاتها
ثوابت بالكود لا جداول (حسب قرار المشروع الموثق).
تُستخدم لحساب فئة المانح لحظياً من مجموع منحه بالسنة الحالية.
"""

# كل عنصر: (الحد الأدنى شامل، الحد الأعلى غير شامل أو None لللانهاية، الاسم العربي)
DONOR_CATEGORIES = [
    (10_000_000, None, "البلاتينية"),
    (5_000_000, 10_000_000, "الألماسية"),
    (2_000_000, 5_000_000, "الذهبية"),
    (1_000_000, 2_000_000, "الفضية"),
    (100_000, 1_000_000, "البرونزية"),
    (50_000, 100_000, "الدرجة الأولى"),
    (25_000, 50_000, "الدرجة الثانية"),
    (0, 25_000, "الدرجة الثالثة"),
]


def get_donor_category(total_amount):
    """
    يحدد فئة المانح بناءً على إجمالي مبلغه (عادة إجمالي السنة الحالية).
    يرجع اسم الفئة العربي، أو None لو المبلغ صفر أو المانح بدون منح بعد.
    """
    if not total_amount or total_amount <= 0:
        return None
    for min_amount, max_amount, name_ar in DONOR_CATEGORIES:
        if max_amount is None:
            if total_amount >= min_amount:
                return name_ar
        elif min_amount <= total_amount < max_amount:
            return name_ar
    return None


# لون نص كل فئة (مطابق لفيقما بالضبط) — يُستخدم بصفحات القوائم البسيطة
# مثل "الجهات المانحة" عند المستفيد، وليس شارة الهوية الموحّدة الخضراء
CATEGORY_COLORS = {
    "البلاتينية": "text-slate-500",
    "الألماسية": "text-sky-600",
    "الذهبية": "text-[#B8860B]",
    "الفضية": "text-gray-500",
    "البرونزية": "text-[#8B4513]",
    "الدرجة الأولى": "text-teal-600",
    "الدرجة الثانية": "text-cyan-600",
    "الدرجة الثالثة": "text-lime-600",
}


def get_category_color(category_name):
    """يرجع كلاس Tailwind للون النص المطابق للفئة، أو لون افتراضي رمادي."""
    return CATEGORY_COLORS.get(category_name, "text-[#4d5761]")